import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { CompilerPin } from './types.ts';
const root = fileURLToPath(new URL('../', import.meta.url));
const pin: CompilerPin = JSON.parse(readFileSync(new URL('../compiler-source.json', import.meta.url), 'utf8'));
function run(command: string, args: string[]) {
  const r = spawnSync(command, args, { cwd: root, stdio: 'inherit' });
  if (r.error || r.status !== 0) throw r.error ?? new Error(`${command} exited ${r.status}`);
}
run('rustup', ['toolchain', 'install', pin.rust, '--profile', 'minimal', '--target', pin.target]);
run('cargo', [`+${pin.rust}`, 'install', 'wasm-bindgen-cli', '--version', pin.wasmBindgen, '--locked', '--root', `${root}.build/tools`]);
// The licence notices shipped with @typfolio/wasm are generated by cargo-about (tools/about.toml). Its binary needs
// the `cli` feature, which is off by default.
run('cargo', [`+${pin.rust}`, 'install', 'cargo-about', '--version', pin.cargoAbout, '--locked', '--features', 'cli', '--root', `${root}.build/tools`]);
